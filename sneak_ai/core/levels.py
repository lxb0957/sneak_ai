# ============ 建造工具 ============
def flood_floor(m: GridMap, sx: int, sy: int) -> set:
    """从 (sx, sy) 出发在可走格上做 BFS，返回可达格集合。"""
    seen = {(sx, sy)}
    stack = [(sx, sy)]
    while stack:
        x, y = stack.pop()
        for nx, ny in ((x + 1, y), (x - 1, y), (x, y + 1), (x, y - 1)):
            if (nx, ny) in seen or m.is_wall(nx, ny):
                continue
            seen.add((nx, ny))
            stack.append((nx, ny))
    return seen


def carve(m: GridMap, x0: int, y0: int, x1: int, y1: int) -> None:
    """把一块矩形从岩体里挖空（闭区间）。"""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            m.set_floor(x, y)


def fill(m: GridMap, x0: int, y0: int, x1: int, y1: int) -> None:
    """把一块矩形填成岩体（挖过头了要和 carve 对称地用）。"""
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            m.set_wall(x, y)


def add_cover(m: GridMap, blocks, spawn, protected=()) -> list:
    """往已经挖好的房间里放柱子 / 货箱，边放边做可达性校验。

    为什么必须校验：一块 2x3 的货箱如果正好卡在小房间的转折处，
    整个房间会被切成两半 —— 玩家过不去，敌人的 A* 也会失效，
    而这种"看起来没事"的关卡 bug 只能靠 flood fill 兜住。
    """
    placed = []
    prot = set(protected)
    for (bx, by, bw, bh) in blocks:
        cells = [(bx + dx, by + dy) for dx in range(bw) for dy in range(bh)]
        if any(m.is_wall(cx, cy) for cx, cy in cells):
            continue   # 已经有墙/柱子了，叠上去没意义
        if any((cx, cy) in prot for cx, cy in cells):
            continue   # 门口、目标点周围必须保持畅通
        for cx, cy in cells:
            m.set_wall(cx, cy)
        reach = flood_floor(m, int(spawn[0]), int(spawn[1]))
        total = sum(1 for y in range(m.h) for x in range(m.w) if not m.is_wall(x, y))
        if len(reach) < total:
            for cx, cy in cells:
                m.set_floor(cx, cy)
            continue
        placed.append((bx, by, bw, bh))
    return placed


def snap_to_floor(grid, x: float, y: float) -> tuple:
    """把坐标吸附到最近的空格中心（原地是墙时按半径扩散找）。"""
    cx, cy = int(x), int(y)
    if not grid.is_wall(cx, cy):
        return (x, y)
    for r in range(1, 8):
        best = None
        best_d = 1e9
        for dx in range(-r, r + 1):
            for dy in range(-r, r + 1):
                nx, ny = cx + dx, cy + dy
                if grid.is_wall(nx, ny):
                    continue
                d = dx * dx + dy * dy
                if d < best_d:
                    best_d, best = d, (nx, ny)
        if best is not None:
            return (best[0] + 0.5, best[1] + 0.5)
    return (x, y)


def _check_connected(m: GridMap, sx: int, sy: int) -> None:
    """构建期连通性自检：任何一块该到的区域到不了，立刻报错。

    关卡是手写坐标，写错一个数字就会挖出一条死路 —— 让它在构建期就炸掉，
    而不是等玩家走到墙前面才发现。

    用"可达格数 == 总可走格数"做全图校验，而不是只抽查几个坐标：
    抽查点很容易刚好落在柱子上（我第一次写就撞了），校验本身反而变成噪音。
    """
    reach = flood_floor(m, sx, sy)
    floors = [(x, y) for y in range(m.h) for x in range(m.w) if not m.is_wall(x, y)]
    if len(reach) != len(floors):
        orphans = sorted(set(floors) - reach)[:6]
        raise RuntimeError(
            f"关卡不连通：{len(floors) - len(reach)} 个可走格从出生点不可达，"
            f"例如 {orphans}"
        )


