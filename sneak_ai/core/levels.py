def build_ring() -> GridMap:
    """80x60 的"环形枢纽"：一圈外环走廊 + 四条辐条，中央是金库。

    开挖顺序和第一关一致（先填满岩体再挖），只是这次挖的形状是一圈闭合的环。
    环的好处是"永远有另一条路"，坏处是**玩家可以绕圈风筝追兵** ——
    所以环上插了 8 道闸（横截面收窄到 2 格），把一整圈切成 8 段。
    每段都能走，但没有一段能一口气跑完。
    """
    W, H = 80, 60
    m = GridMap.filled(W, H)

    # ---- 1. 外环走廊：4 格宽的一圈 ----
    carve(m, 6, 4, 73, 7)      # 北
    carve(m, 6, 52, 73, 55)    # 南
    carve(m, 6, 8, 9, 51)      # 西
    carve(m, 70, 8, 73, 51)    # 东

    # ---- 2. 中央金库 + 一条辐条（北）----
    # v1.5 改了两轮，两轮都是机器人教的：
    # 第一版四条辐条 → 46 秒，它从南辐条进、西辐条出，一条 L 形，全程没碰金库里的两个人。
    # **四个口等于没有口**（和第 3 关四道门是同一个错）。
    # 第二版封掉东西、留南北 → 44 秒，反而更快：南辐条本身就是最短路径，
    # 封掉的两条它本来也没走，而"南进北出"并不比"南进南出"长多少。
    # 第三版只留北辐条 → 出生点在西南，金库在北边正中，去和回都得绕西廊 + 北廊，
    # 而且进出都要连过两道闸（北廊 x=20 / x=59）。这一版才真正改变了路程。
    carve(m, 44, 14, 59, 29)   # 金库 16x16，中心 (52, 22)
    carve(m, 51, 8, 52, 13)    # 北辐条（金库 → 北廊）—— 唯一入口
    # 原来的东西南三条辐条的位置改成内墙凹室：从外环往里挖 3 格，
    # 够一个人缩进去躲，但走到头是死路 —— 保留"有个地方能贴一下"，
    # 拿掉"从这儿抄近道进金库"。必须从**外环**那侧挖，
    # 紧贴金库墙挖一格就等于又开了一道门，白改。
    carve(m, 10, 21, 12, 22)   # 西侧凹室（自西廊向内）
    carve(m, 67, 21, 69, 22)   # 东侧凹室（自东廊向内）
    carve(m, 51, 49, 52, 51)   # 南侧凹室（自南廊向内）

    # ---- 2.6 设备间：封掉三条辐条后，环内空出来三大块岩体 ----
    # 俯视图上那三块就是纯空白。挖成设备间填进去：各自只从**外环**开一个口，
    # 互不相通、也不通金库 —— 提供掩体和补给，但不提供进金库的捷径。
    # （这也是"删掉一条路"之后必须补回来的东西：玩家少了选择，
    #   不能连"躲的地方"一起少掉。）
    carve(m, 10, 31, 17, 37)    # 西设备间（自西廊）
    carve(m, 62, 31, 69, 37)    # 东设备间（自东廊）
    carve(m, 24, 44, 32, 51)    # 南设备间（自南廊）

    # ---- 2.5 壁龛：沿内墙挖 8 个凹室 ----
    # 这是机器人跑出来的教训。第一版没有壁龛，测试机器人 29 秒死在南廊：
    # 它被哨兵看见后按"找掩体"的规则就近躲进了 2 格宽的南辐条 ——
    # 一条 2 格宽、22 格长的死胡同，被追进来就再没有第二个出口。
    # 玩家会遇到一模一样的事：环形走廊是一整条长直道，中间没有任何地方可以"让一下"，
    # 被看见就只剩"跑"这一个动词。
    # 壁龛给的是第三个动词：**躲进去等它走过去**。
    for (x0, y0, x1, y1) in (
        (11, 8, 13, 10), (66, 8, 68, 10),      # 北廊两处
        # 南廊这两处必须挖到 y=51：内墙是 y8..51，南廊从 y52 起，
        # 只挖到 y=50 就会留下一格墙，壁龛变成孤岛（构建期连通性校验当场拦下）。
        (11, 49, 13, 51), (66, 49, 68, 51),    # 南廊两处
        (10, 10, 12, 12), (10, 42, 12, 44),    # 西廊两处
        (67, 10, 69, 12), (67, 42, 69, 44),    # 东廊两处
    ):
        carve(m, x0, y0, x1, y1)

    # ---- 3. 环上打 8 道闸 ----
    for (hole, wall, _name) in RING_GATES:
        fill(m, *wall)
        carve(m, *hole)

    # ---- 4. 闸口与补给点附近保持空旷，其余地方摆柱子 ----
    protected = set()
    for (hole, _wall, _name) in RING_GATES:
        hx0, hy0, hx1, hy1 = hole
        for dx in range(-2, 3):
            for dy in range(-2, 3):
                protected.add((hx0 + dx, hy0 + dy))
                protected.add((hx1 + dx, hy1 + dy))
    for (px, py, _kind) in RING_PICKUPS:
        for dx in range(-1, 2):
            for dy in range(-1, 2):
                protected.add((px + dx, py + dy))

    add_cover(m, [
        # 金库四角的柱子：给"拿了数据就跑"留掩体，但不挡住终端 (52,22)。
        # 柱子刻意摆在 x45~46 / x58~59，因为金库的两个哨兵巡 x=47 和 x=56 ——
        # 柱子压住巡逻线的话，snap_to_floor 会把巡逻点挪走，哨兵的走位就变形了。
        (45, 16, 2, 2), (58, 16, 2, 2), (45, 27, 2, 2), (58, 27, 2, 2),
        # 终端四周的四根"神龛柱"。
        # 这是第二次机器人测试逼出来的：16x16 的空场里，哨兵站哪都能一眼看穿，
        # 玩家走进去到摸到终端这几秒是"全程被盯着"，机器人在 (52,23) 死了三次 ——
        # 差一格摸到终端。柱子给的是这么一条路：贴着柱子一格一格挪，
        # 让视锥在柱子后面断开，而不是赌哨兵什么时候转身。
        (49, 19, 2, 2), (53, 19, 2, 2), (49, 23, 2, 2), (53, 23, 2, 2),
        # 外环边上偶尔一个货箱：只贴一侧放，走廊始终留 3 格能过
        (30, 4, 2, 1), (48, 7, 2, 1),
        (30, 55, 2, 1), (48, 52, 2, 1),
        (6, 30, 1, 2), (9, 46, 1, 2),
        (73, 30, 1, 2),
    ], (7.5, 52.5), protected)

    _check_connected(m, 7, 52)
    return m


