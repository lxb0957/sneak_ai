# ============ 注册表 ============
@dataclass(frozen=True)
class Level:
    """一关的全部数据。构建器是函数，其余是纯数据。"""

    idx: int
    name: str
    subtitle: str          # 一句话描述这张图想让玩家紧张什么
    build: Callable[[], GridMap]
    patrols: tuple
    pickups: tuple
    doors: tuple           # (洞矩形, 名字) 统一成两元组，审计脚本只关心洞
    # 数据节点：1 个 = 老玩法（走过去摸一下）；2 个 = 这一关要走两条腿。
    # 为什么用元组而不是"再加一个 terminal2"：审计脚本、小地图、HUD 都要
    # 遍历目标点，"数量"本身是关卡参数，不该在代码里写死成 1 或 2。
    terminals: tuple       # 数据节点（连续坐标，按建议顺序排，玩法上无强制顺序）
    exfil: tuple           # 撤离点（连续坐标）
    spawn: tuple           # 玩家出生点（连续坐标）
    par: Tuple[float, float, float]   # 评级基准 (S, A, B) 秒
    # 这一关哨兵的追击速度。玩家走路 4.4 / 冲刺 6.5，所以：
    #   < 4.0  走路能拉开距离（第 1 关，教学）
    #   = 4.0  走路拉不开，得用冲刺（第 2 关）
    #   = 4.4  和走路一样快，冲刺以外没得商量（第 3 关）
    chase: float = C.ENEMY_CHASE_SPEED
    # 警报（拿到数据后的全图封锁）强度也按关卡给。三个值一起决定"回程有多硬"：
    #   第 1 关 4.0 / 8.0 / 20s —— 追兵仍慢于走路，警报只是"该走了"的提醒
    #   第 2 关 4.3 / 8.5 / 30s —— 默认值，得跑起来
    #   第 3 关 4.6 / 9.0 / 40s —— 比走路快，进入封锁就只能冲刺
    # 之前三关共用一套默认值，结果是**教学关最难**（12 相位 25% 胜），
    # 因为第 1 关路程最长、还要原路折返，警报对它的惩罚最重。
    alert_speed: float = C.ALERT_SPEED_CHASE
    alert_view: float = C.ALERT_VIEW_RANGE
    alert_duration: float = C.ALERT_DURATION

    @property
    def terminal(self) -> tuple:
        """第一个数据节点。老脚本（审计/测试/预览）只认单目标，保留这个别名。"""
        return self.terminals[0]


