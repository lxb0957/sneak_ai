def cumulative_par(idx: int) -> Tuple[float, float, float]:
    """打到第 idx 关时允许的**累计**用时基准 (S, A, B)。

    为什么要累计：多关之后 `world.elapsed` 是整局累计的，如果评级仍然拿
    第 2 关的单关基准去比，玩家越往后越容易拿 S —— 打两关用 120 秒还能评 S，
    评级就不再是"效率"的度量，而是"关卡数"的函数。
    """
    upto = LEVELS[: idx + 1]
    return (
        sum(lv.par[0] for lv in upto),
        sum(lv.par[1] for lv in upto),
        sum(lv.par[2] for lv in upto),
    )


def spawn_and_patrols(level: Level, grid=None):
    """返回 (玩家出生点, 敌人生成配置列表)。

    配置里的坐标是整数格点，而整数坐标正好落在 4 个格子的公共**角点**上。
    圆形碰撞用"圆心到墙格最近点距离"，角点接触距离恰好为 0，会被判定为一直在
    墙里 —— 结果就是所有敌人开局被钉死在原地。所以统一 +0.5 转成格中心。
    """
    cfg_centered = [
        (x + 0.5, y + 0.5, [(px + 0.5, py + 0.5) for px, py in pts])
        for (x, y, pts) in level.patrols()
    ]

    # 柱子/货箱可能正好盖住手工写的巡逻点。这里做一次吸附：
    # 落在墙里的点挪到最近的空格，避免"哨兵卡在墙里不动"这种查半天
    # 查不出来的关卡 bug（也是我踩过的坑）。
    if grid is not None:
        cfg_centered = [
            (*snap_to_floor(grid, x, y),
             [snap_to_floor(grid, px, py) for px, py in pts])
            for (x, y, pts) in cfg_centered
        ]
    return level.spawn, cfg_centered


def level_pickups(level: Level, grid=None):
    """返回补给点列表：每项 = {"x", "y", "kind", "taken"}。

    坐标同样 +0.5 转成格中心，并且落在柱子/货箱里的点会被吸附出来，
    避免出现"看得见却永远捡不到"的补给。
    """
    out = []
    for (x, y, kind) in level.pickups:
        px, py = x + 0.5, y + 0.5
        if grid is not None:
            px, py = snap_to_floor(grid, px, py)
        out.append({"x": px, "y": py, "kind": kind, "taken": False})
    return out


