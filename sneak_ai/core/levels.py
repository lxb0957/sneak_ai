# ============ 第 2 关：环形枢纽 ============
# 设计意图与第 1 关**故意相反**：
#
# | 维度 | 第 1 关（哨站） | 第 2 关（环形枢纽） |
# |---|---|---|
# | 走廊宽 | 2~3 格（只能侧身） | 4 格（能贴对面墙走） |
# | 拓扑 | 两条弧 + 一条捷径（不对称） | 一圈环 + 四条辐条（四向对称） |
# | 视线 | 短，靠门切断 | 长，走廊里能看穿一整段 |
# | 难点 | 等门窗口 | 等在走廊里迎面走来的人转身 |
# | 压力来源 | 门多而密 | 门少，但一进走廊就无处可藏 |
#
# 4 格宽走廊是这张图的性格：它给了"从对面墙侧身滑过去"的可能（第 1 关
# 的 2 格门完全没有这个选项），代价是走廊内的视线也长了一倍 ——
# 站在原地观察的人会先看见你。所以这里的正确做法不是"等门空"，是"跟着
# 巡逻兵的后背走"。
#
# 中央金库四面开口 = 最小割 4，和第 1 关一致。四条辐条都是**真路**：
# 最早我把南辐条中途堵死想做个"走错白跑"的陷阱，字符图一画就发现
# 这等于砍掉三分之一的进攻方向 —— 玩家从南边过来时只剩"原路返回"，
# 那不是取舍，那是惩罚。陷阱要靠"看起来能走、进去才知道不行"，
# 不能直接砍掉主路。
