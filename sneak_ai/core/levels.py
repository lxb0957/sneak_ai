def build_hall() -> GridMap:
    """80x60 的"柱林中庭"：3 格宽服务廊 + 56x40 大厅 + 九个纵列 x 六个横排的柱林。"""
    W, H = 80, 60
    m = GridMap.filled(W, H)

    # ---- 1. 外圈服务廊：3 格宽 ----
    carve(m, 5, 4, 74, 6)      # 北
    carve(m, 5, 53, 74, 55)    # 南
    carve(m, 5, 7, 7, 52)      # 西
    carve(m, 72, 7, 74, 52)    # 东

    # ---- 2. 大厅 ----
    carve(m, 12, 10, 67, 49)

    # ---- 3. 两道 2 格宽的门洞（对齐柱缝，别让玩家一进门就撞柱子）----
    for rect in HALL_DOORWAYS:
        carve(m, *rect)

    # ---- 4. 柱林（奇数行右移 3 格 → 没有一条直街）----
    # 柱距 6（柱子 2 格 + 空隙 4 格）。空隙 4 格是关键数字：
    # 小于 3 就变成迷宫（玩家只能一格一格挪，节奏全掉）；
    # 大于 5 就变成空地（柱子挡不住视线，等于没有柱林）。
    #
    # 光有柱距还不够 —— 正交网格的柱林横竖都是通街，玩家可以沿一条街走到头。
    # 所以奇数行整体右移 3 格（= 缝宽的一半），相邻两行的通道互相错开：
    # 你从一条缝往北走，走到下一行就撞上柱子，必须横移 3 格找下一个口。
    # 这就是"Z 字蛇行"的来源，也是这一关唯一一处靠地形而不是靠人数增加的路程。
    pillars = []
    for row_i, py in enumerate(HALL_ROWS):
        off = HALL_STAGGER if row_i % 2 else 0
        for px in HALL_COLS:
            x0 = px + off
            if x0 + 1 > 67:          # 别顶到大堂东墙
                continue
            pillars.append((x0, py, 2, 2))

    protected = set()
    for (x0, y0, x1, y1) in HALL_DOORWAYS:
        for dx in range(-2, 3):
            for dy in range(-2, 3):
                protected.add((x0 + dx, y0 + dy))
                protected.add((x1 + dx, y1 + dy))
    for (cx, cy) in (*HALL_TERMINALS, HALL_SPAWN, HALL_EXFIL):
        # 只保护 ±1（3x3）：终端刻意放在柱林中间的一个"格子"里，
        # 四角有柱子 —— 那是这一关唯一必须"走进去"的地方。
        # v1.4 的保护圈是 ±2（5x5），顺手把终端周围的柱子删掉，
        # 结果终端站在一小片空场上，"柱林"到那儿就断了。
        for dx in range(-1, 2):
            for dy in range(-1, 2):
                protected.add((int(cx) + dx, int(cy) + dy))
    for (px, py, _kind) in HALL_PICKUPS:
        for dx in range(-1, 2):
            for dy in range(-1, 2):
                protected.add((px + dx, py + dy))

    add_cover(m, pillars, (int(HALL_SPAWN[0]), int(HALL_SPAWN[1])), protected)

    _check_connected(m, int(HALL_SPAWN[0]), int(HALL_SPAWN[1]))
    return m


